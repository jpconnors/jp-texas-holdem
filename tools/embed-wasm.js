#!/usr/bin/env node
// Wraps a compiled .wasm file in a small JS file (base64) so the page can load it even from file://.
// Usage: node tools/embed-wasm.js <input.wasm> <output.js>
'use strict';
const fs = require('fs');

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error('Usage: node tools/embed-wasm.js <input.wasm> <output.js>');
  process.exit(1);
}
const bytes = fs.readFileSync(input);
const b64 = bytes.toString('base64');
const lines = b64.match(/.{1,120}/g) || [];
const js = `/* GENERATED by tools/embed-wasm.js from engine/ (Rust). Do not edit by hand. */
(function (root) {
  (root.Poker = root.Poker || {}).WASM_BASE64 =
${lines.map((l) => `    '${l}'`).join(' +\n')};
})(typeof window !== 'undefined' ? window : globalThis);
`;
fs.writeFileSync(output, js);
console.log(`Embedded ${input} (${(bytes.length / 1024).toFixed(0)} KB) -> ${output}`);
